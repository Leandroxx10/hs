const { test } = require('node:test');
const assert = require('node:assert/strict');
const { mkdtempSync, writeFileSync, readFileSync, rmSync } = require('node:fs');
const { tmpdir } = require('node:os');
const path = require('node:path');
const { once } = require('node:events');

test('argumentos preservam caminhos com espaços e caracteres de shell', async t => {
  const { validateConfig, buildArgs } = await import('../electron/engine.mjs');
  const { defaults } = await import('../shared/model.mjs');
  const dir = mkdtempSync(path.join(tmpdir(), 'hs test '));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const hashFile = path.join(dir, 'rede & teste.22000');
  const wordlist = path.join(dir, 'palavras ; teste.txt');
  writeFileSync(hashFile, `WPA*01*${'a'.repeat(32)}*001122334455*66778899aabb*54455354***\n`);
  writeFileSync(wordlist, 'Senha123');
  const config = validateConfig({ ...defaults, hashFile, wordlist, attack: 'dictionary' });
  const args = buildArgs('audit', config, dir);
  assert.ok(args.includes(hashFile)); assert.ok(args.includes(wordlist));
  assert.equal(args.filter(v => v === hashFile).length, 1);
  assert.throws(() => validateConfig({ ...config, deviceIds: '1 --force' }));
  assert.throws(() => validateConfig({ ...config, workload: 99 }));
  writeFileSync(hashFile, 'não é um hash WPA');
  assert.throws(() => validateConfig(config));
});
test('sessões isolam potfile, resultados e restore; benchmark dispensa arquivo', async () => {
  const { buildArgs } = await import('../electron/engine.mjs');
  const { defaults } = await import('../shared/model.mjs');
  const dir = path.resolve('job-test');
  const args = buildArgs('audit', { ...defaults, minLength: 8, maxLength: 10, hashFile: path.resolve('test.22000') }, dir);
  assert.equal(args[args.indexOf('--increment-min') + 1], '8');
  assert.equal(args[args.indexOf('--increment-max') + 1], '10');
  assert.equal(args.at(-1), '?1'.repeat(10));
  assert.equal(args[args.indexOf('--potfile-path') + 1], path.join(dir, 'results.potfile'));
  assert.deepEqual(buildArgs('benchmark', {}, dir), ['-b', '-m', '22000']);
  assert.ok(buildArgs('restore', {}, dir).includes('--restore'));
});
test('motor distingue sucesso, erro, interrupção e execução concorrente', { skip: process.platform === 'win32' }, async t => {
  const { Engine } = await import('../electron/engine.mjs');
  const root = mkdtempSync(path.join(tmpdir(), 'hs-engine-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const executable = path.join(root, 'hashcat');
  writeFileSync(executable, '#!/bin/sh\nif [ "$1" = "-b" ]; then echo "Speed.#1.........: 4.5 kH/s"; exit 0; fi\nexit 255\n', { mode: 0o755 });
  const engine = new Engine(path.join(root, 'data'));
  engine.setExecutable(executable);
  let done = once(engine, 'finished');
  engine.start('benchmark');
  assert.throws(() => engine.start('benchmark'), /Já existe/);
  const [benchmark] = await done;
  assert.equal(benchmark.status, 'completed'); assert.equal(engine.benchmark.rate, 4500);
  done = once(engine, 'finished'); engine.start('devices');
  assert.equal((await done)[0].status, 'error');
  writeFileSync(executable, '#!/bin/sh\nexec sleep 30\n', { mode: 0o755 });
  done = once(engine, 'finished'); engine.start('benchmark'); engine.stop();
  assert.equal((await done)[0].status, 'interrupted');
  assert.equal(new Engine(path.join(root, 'data')).benchmark.rate, 4500);
  assert.ok(!JSON.stringify(engine.report()).includes('logs'));
  const state = JSON.parse(readFileSync(path.join(root, 'data', 'state.json'), 'utf8'));
  state.history[0].status = 'running';
  writeFileSync(path.join(root, 'data', 'state.json'), JSON.stringify(state));
  assert.equal(new Engine(path.join(root, 'data')).history[0].status, 'interrupted');
});
